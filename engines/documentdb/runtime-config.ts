import { isAbsolute } from 'path'

// DocumentDB's GA gateway authenticates its PostgreSQL connections with peer
// authentication. The MongoDB listener has its own SCRAM credentials.
export const DOCUMENTDB_GATEWAY_ROLE = 'spindb_gateway'

function assertPort(port: number): void {
  if (!Number.isInteger(port) || port < 1 || port > 65535) {
    throw new Error(`Invalid DocumentDB port: ${port}`)
  }
}

function pgLiteral(value: string): string {
  if (/[\r\n\0]/.test(value)) {
    throw new Error(
      'PostgreSQL configuration values cannot contain control characters',
    )
  }
  return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "''")}'`
}

export function buildPostgresConfig(options: {
  socketDirectory: string
  port: number
}): string {
  assertPort(options.port)
  if (!isAbsolute(options.socketDirectory)) {
    throw new Error('DocumentDB requires an absolute private socket directory')
  }
  // The longest PostgreSQL socket filename is /.s.PGSQL.65535. Linux sockaddr_un
  // has a 108-byte limit, including the terminating NUL.
  if (Buffer.byteLength(options.socketDirectory) + 15 >= 108) {
    throw new Error(
      'DocumentDB socket path is too long; use a shorter SPINDB_HOME',
    )
  }
  return [
    "listen_addresses = ''",
    `port = ${options.port}`,
    `unix_socket_directories = ${pgLiteral(options.socketDirectory)}`,
    'unix_socket_permissions = 0700',
    `documentdb.localhost_connection_string = ${pgLiteral("host='" + options.socketDirectory.replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'")}`,
    "shared_preload_libraries = 'pg_cron,pg_documentdb_core,pg_documentdb,pg_documentdb_extended_rum'",
    "cron.database_name = 'postgres'",
    'cron.launch_active_jobs = off',
    "log_statement = 'none'",
    "log_min_error_statement = 'panic'",
    '',
  ].join('\n')
}

export function buildPeerAuthentication(osUsername: string): {
  hba: string
  ident: string
} {
  // PostgreSQL ident records are whitespace-delimited. Reject unsupported OS
  // account names rather than interpolating an additional mapping or rule.
  if (!/^[a-zA-Z_][a-zA-Z0-9_.-]*\$?$/.test(osUsername)) {
    throw new Error(
      'Unsupported OS account name for DocumentDB peer authentication',
    )
  }
  const roles = [
    'postgres',
    DOCUMENTDB_GATEWAY_ROLE,
    'documentdb_bg_worker_role',
    '+documentdb_admin_role',
    '+documentdb_readwrite_role',
    '+documentdb_readonly_role',
  ]
  return {
    hba: 'local all all peer map=spindb_documentdb\n',
    ident:
      roles
        .map((role) => `spindb_documentdb ${osUsername} ${role}`)
        .join('\n') + '\n',
  }
}

export function buildGatewayConfig(options: {
  socketDirectory: string
  backendPort: number
  port: number
  bindAddress?: string
}): Record<string, unknown> {
  assertPort(options.port)
  assertPort(options.backendPort)
  // Keep the first native implementation local. Remote TLS qualification must
  // precede exposing the SCRAM listener on other interfaces.
  if (options.bindAddress && options.bindAddress !== '127.0.0.1') {
    throw new Error('DocumentDB currently supports --bind 127.0.0.1 only')
  }
  return {
    NodeHostName: 'localhost',
    BlockedRolePrefixes: [
      'documentdb',
      'citus',
      'pg',
      'internal_role',
      'spindb_',
    ],
    PostgresSystemUser: DOCUMENTDB_GATEWAY_ROLE,
    PostgresDataUser: DOCUMENTDB_GATEWAY_ROLE,
    PostgresHostName: options.socketDirectory,
    PostgresPort: options.backendPort,
    PostgresDatabase: 'postgres',
    GatewayListenPort: options.port,
    UseLocalHost: true,
    EnforceTls: false,
    EnableV2Runtime: true,
    AsyncRuntimeWorkerThreads: 2,
    CertificateOptions: { CertType: 'PemAutoGenerated' },
    TelemetryOptions: {
      ServiceName: 'documentdb_gateway',
      Metrics: { Enabled: false },
      Tracing: { Enabled: false },
    },
  }
}
